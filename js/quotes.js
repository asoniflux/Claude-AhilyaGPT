var currentQuoteIndex = 0;
var quoteAutoTimer = null;

function initQuotes() {
  var container = document.getElementById('quotes-carousel');
  if (!container) return;

  renderQuote(0);

  // Auto-rotate every 8 seconds
  quoteAutoTimer = setInterval(function () {
    currentQuoteIndex = (currentQuoteIndex + 1) % historicalQuotes.length;
    renderQuote(currentQuoteIndex);
  }, 8000);

  // Nav buttons
  document.getElementById('quote-prev').addEventListener('click', function () {
    clearInterval(quoteAutoTimer);
    currentQuoteIndex = (currentQuoteIndex - 1 + historicalQuotes.length) % historicalQuotes.length;
    renderQuote(currentQuoteIndex);
  });

  document.getElementById('quote-next').addEventListener('click', function () {
    clearInterval(quoteAutoTimer);
    currentQuoteIndex = (currentQuoteIndex + 1) % historicalQuotes.length;
    renderQuote(currentQuoteIndex);
  });

  // Dot navigation
  document.getElementById('quote-dots').addEventListener('click', function (e) {
    var dot = e.target.closest('.quote-dot');
    if (!dot) return;
    clearInterval(quoteAutoTimer);
    currentQuoteIndex = parseInt(dot.dataset.index);
    renderQuote(currentQuoteIndex);
  });

  // Listen for language changes
  EventBus.on('lang:changed', function () {
    renderQuote(currentQuoteIndex);
  });
}

function renderQuote(index) {
  var q = historicalQuotes[index];
  var lang = currentLang || 'en';

  var quoteText = document.getElementById('quote-text');
  var quoteAuthor = document.getElementById('quote-author');
  var quoteContext = document.getElementById('quote-context');
  var quoteType = document.getElementById('quote-type');

  if (!quoteText) return;

  // Fade out
  var card = document.getElementById('quote-card');
  card.classList.remove('quote-card--visible');

  setTimeout(function () {
    quoteText.textContent = q.quote[lang] || q.quote.en;
    quoteAuthor.textContent = q.author[lang] || q.author.en;
    quoteContext.textContent = q.context[lang] || q.context.en;

    var typeLabels = {
      ahilya: { en: 'Her Own Words', hi: 'उनके अपने शब्द', mr: 'त्यांचे स्वतःचे शब्द' },
      historian: { en: 'Historian', hi: 'इतिहासकार', mr: 'इतिहासकार' },
      leader: { en: 'Indian Leader', hi: 'भारतीय नेता', mr: 'भारतीय नेता' },
      scholar: { en: 'Modern Scholar', hi: 'आधुनिक विद्वान', mr: 'आधुनिक विद्वान' }
    };
    quoteType.textContent = typeLabels[q.type][lang] || typeLabels[q.type].en;
    quoteType.className = 'quote-type quote-type--' + q.type;

    // Update dots
    document.querySelectorAll('.quote-dot').forEach(function (dot, i) {
      dot.classList.toggle('quote-dot--active', i === index);
    });

    // Fade in
    card.classList.add('quote-card--visible');
  }, 300);
}
